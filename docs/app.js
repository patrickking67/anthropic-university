  // ---- practice -----------------------------------------------------------
  function renderPractice(exam) {
    var st = store.practice[exam.examId] || (store.practice[exam.examId] = { pos: 0, answers: {}, flags: {} });
    st.answers = st.answers || {};
    st.flags = st.flags || {};
    var domainFilter = "all";
    var viewFilter = "all"; // all | unanswered | flagged | missed
    var wrap = el("div", { class: "view-enter" });
    appEl.appendChild(wrap);

    function list() {
      return (exam.questions || []).filter(function (q) {
        if (domainFilter !== "all" && q.domain !== domainFilter) return false;
        if (viewFilter === "unanswered") return !st.answers[q.id];
        if (viewFilter === "flagged") return !!st.flags[q.id];
        if (viewFilter === "missed") return st.answers[q.id] && st.answers[q.id] !== q.answer;
        return true;
      });
    }

    function draw() {
      clear(wrap);
      wrap.appendChild(crumb(exam, "Practice"));
      wrap.appendChild(modeNav(exam, "practice"));

      var sel = el("select", {
        "aria-label": "Filter by domain",
        onchange: function (e) { domainFilter = e.target.value; st.pos = 0; draw(); },
      });
      sel.appendChild(el("option", { value: "all", text: "All domains" }));
      (exam.domains || []).forEach(function (d) {
        sel.appendChild(el("option", { value: d.id, text: d.name }));
      });
      sel.value = domainFilter;

      var viewSel = el("select", {
        "aria-label": "Filter by progress",
        onchange: function (e) { viewFilter = e.target.value; st.pos = 0; draw(); },
      });
      [
        ["all", "All questions"],
        ["unanswered", "Unanswered"],
        ["missed", "Missed"],
        ["flagged", "Flagged"],
      ].forEach(function (pair) {
        viewSel.appendChild(el("option", { value: pair[0], text: pair[1] }));
      });
      viewSel.value = viewFilter;

      var answeredCount = Object.keys(st.answers).length;
      var correctCount = (exam.questions || []).filter(function (q) {
        return st.answers[q.id] === q.answer;
      }).length;
      wrap.appendChild(el("div", { class: "toolbar" }, [
        el("div", { class: "group" }, [sel, viewSel]),
        el("div", { class: "group" }, [
          el("span", { class: "counter", text: answeredCount + " answered · " + correctCount + " correct" }),
          el("span", { class: "kbd-hint", html: "<kbd>A</kbd>–<kbd>D</kbd> · <kbd>←</kbd><kbd>→</kbd>" }),
          el("button", {
            class: "btn small ghost",
            onclick: function () {
              if (confirm("Reset practice progress for this track?")) {
                st.answers = {};
                st.flags = {};
                st.pos = 0;
                persist();
                draw();
              }
            },
            text: "Reset",
          }),
        ]),
      ]));

      var qs = list();
      if (!qs.length) {
        wrap.appendChild(el("div", { class: "empty-state" }, [
          el("h3", { text: "Nothing in this filter" }),
          el("p", { text: "Try another domain or progress filter, or reset practice progress." }),
          el("button", {
            class: "btn",
            onclick: function () { viewFilter = "all"; domainFilter = "all"; st.pos = 0; draw(); },
            text: "Show all questions",
          }),
        ]));
        return;
      }
      if (st.pos >= qs.length) st.pos = qs.length - 1;
      if (st.pos < 0) st.pos = 0;
      var q = qs[st.pos];
      var picked = st.answers[q.id] || null;

      function pick(L) {
        if (picked) return;
        st.answers[q.id] = L;
        persist();
        draw();
      }
      function go(delta) {
        st.pos = Math.max(0, Math.min(qs.length - 1, st.pos + delta));
        persist();
        draw();
      }

      bindKeys(function (e) {
        if (typingTarget(e) || e.metaKey || e.ctrlKey || e.altKey) return;
        var key = e.key.toUpperCase();
        if (LETTERS.indexOf(key) !== -1) { e.preventDefault(); pick(key); return; }
        if (e.key === "ArrowRight" || e.key === "n") { e.preventDefault(); go(1); return; }
        if (e.key === "ArrowLeft" || e.key === "p") { e.preventDefault(); go(-1); return; }
        if (e.key === "f") {
          e.preventDefault();
          if (st.flags[q.id]) delete st.flags[q.id];
          else st.flags[q.id] = true;
          persist();
          draw();
        }
      });

      var card = el("div", { class: "qcard" });
      card.appendChild(el("div", { class: "progressline" }, [
        el("i", { style: "width:" + ((st.pos + 1) / qs.length * 100) + "%" }),
      ]));
      card.appendChild(el("div", { class: "qmeta" }, [
        q.scenario ? el("span", { class: "scenario", text: q.scenario }) : null,
        q.studyArea ? el("span", { class: "tag", text: q.studyArea }) : null,
        q.difficulty ? el("span", { class: "tag", text: q.difficulty }) : null,
        el("button", {
          class: "flag-btn" + (st.flags[q.id] ? " on" : ""),
          title: "Flag for review (F)",
          onclick: function () {
            if (st.flags[q.id]) delete st.flags[q.id];
            else st.flags[q.id] = true;
            persist();
            draw();
          },
          text: st.flags[q.id] ? "Flagged" : "Flag",
        }),
      ]));
      card.appendChild(el("div", { class: "stem", text: q.stem }));

      var opts = el("div", { class: "options", role: "group", "aria-label": "Answer choices" });
      LETTERS.forEach(function (L) {
        var cls = "opt";
        if (picked) {
          if (L === q.answer) cls += " correct";
          else if (L === picked) cls += " wrong";
        }
        opts.appendChild(el("button", {
          class: cls,
          disabled: picked ? "disabled" : null,
          onclick: picked ? null : function () { pick(L); },
        }, [
          el("span", { class: "key", text: L }),
          el("span", { text: q.options[L] }),
        ]));
      });
      card.appendChild(opts);

      if (picked) {
        var correct = picked === q.answer;
        var fb = el("div", { class: "feedback " + (correct ? "correct" : "wrong") });
        fb.appendChild(el("div", {
          class: "verdict",
          text: correct ? "Correct" : ("Incorrect - the answer is " + q.answer),
        }));
        fb.appendChild(el("p", { text: q.explanationCorrect }));
        if (!correct && q.explanationDistractor) {
          fb.appendChild(el("p", { class: "why", text: "Why " + picked + " misses: " + q.explanationDistractor }));
        }
        if (q.reference) {
          fb.appendChild(el("p", { class: "why" }, [
            el("a", { href: q.reference, target: "_blank", rel: "noopener", text: "Reference ↗" }),
          ]));
        }
        card.appendChild(fb);
      }

      card.appendChild(el("div", { class: "qnav" }, [
        el("button", {
          class: "btn",
          disabled: st.pos === 0 ? "disabled" : null,
          onclick: function () { go(-1); },
          text: "← Previous",
        }),
        el("span", { class: "counter", text: "Question " + (st.pos + 1) + " of " + qs.length }),
        el("button", {
          class: "btn primary",
          disabled: st.pos >= qs.length - 1 ? "disabled" : null,
          onclick: function () { go(1); },
          text: "Next →",
        }),
      ]));
      wrap.appendChild(card);
    }
    draw();
  }

  // ---- exam ---------------------------------------------------------------
  function sampleByDomain(exam, n) {
    var qs = exam.questions || [];
    if (n >= qs.length) return shuffle(qs);
    var byDomain = {};
    qs.forEach(function (q) { (byDomain[q.domain] = byDomain[q.domain] || []).push(q); });
    var picked = [];
    (exam.domains || []).forEach(function (d) {
      var pool = shuffle(byDomain[d.id] || []);
      var want = Math.max(1, Math.round((d.weight || (1 / (exam.domains.length || 1))) * n));
      picked = picked.concat(pool.slice(0, want));
    });
    if (picked.length < n) {
      var remaining = shuffle(qs.filter(function (q) { return picked.indexOf(q) === -1; }));
      picked = picked.concat(remaining.slice(0, n - picked.length));
    }
    return shuffle(picked.slice(0, n));
  }

  function renderExam(exam) {
    var wrap = el("div", { class: "view-enter" });
    appEl.appendChild(wrap);
    var total = (exam.questions || []).length;
    function fmt(s) {
      var m = Math.floor(s / 60);
      var ss = s % 60;
      return (m < 10 ? "0" : "") + m + ":" + (ss < 10 ? "0" : "") + ss;
    }

    function setup() {
      clear(wrap);
      bindKeys(null);
      wrap.appendChild(crumb(exam, "Mock exam"));
      wrap.appendChild(modeNav(exam, "exam"));
      var choices = [{ n: Math.min(20, total), label: "Quick - " + Math.min(20, total) + " questions" }];
      if (total > 40) choices.push({ n: 40, label: "Half - 40 questions" });
      choices.push({ n: total, label: "Full - " + total + " questions" });
      var box = el("div", { class: "qcard" }, [
        el("h3", { text: "Timed mock exam", style: "margin-top:0" }),
        el("p", {
          class: "track-meta",
          text: "Approximate " + exam.meta.scaleMin + "–" + exam.meta.scaleMax + " scale · " + exam.meta.passScaled +
            " to pass · real format " + (exam.meta.timeMinutes || "-") + " min. Questions are sampled across domains by weight. No feedback until you submit.",
        }),
        el("ul", { class: "exam-setup-list" }, [
          el("li", { text: "Flag questions to revisit before submitting." }),
          el("li", { text: "Use the number grid to jump around." }),
          el("li", { text: "Keyboard: A–D to answer, ← → to navigate, F to flag." }),
        ]),
      ]);
      var row = el("div", { class: "mode-row", style: "margin-top:14px" });
      choices.forEach(function (c, idx) {
        row.appendChild(el("button", {
          class: "btn" + (idx === 0 ? " primary" : ""),
          onclick: function () { run(c.n); },
          text: c.label,
        }));
      });
      box.appendChild(row);
      wrap.appendChild(box);
    }

    function run(n) {
      var questions = sampleByDomain(exam, n);
      var answers = {};
      var flags = {};
      var pos = 0;
      var seconds = 0;
      var timer = setInterval(function () {
        seconds++;
        var t = document.getElementById("exam-timer");
        if (t) {
          t.textContent = fmt(seconds);
          var limit = (exam.meta.timeMinutes || 120) * 60;
          var pace = seconds / Math.max(1, questions.length) * questions.length;
          if (pace > limit * 0.85) t.classList.add("warn");
        }
      }, 1000);

      function submit() {
        if (!confirm("Submit and score your exam?")) return;
        clearInterval(timer);
        bindKeys(null);
        results();
      }

      function draw() {
        clear(wrap);
        wrap.appendChild(crumb(exam, "Mock exam"));
        wrap.appendChild(el("div", { class: "toolbar" }, [
          el("div", { class: "group" }, [
            el("span", { class: "exam-timer", id: "exam-timer", text: fmt(seconds) }),
            el("span", { class: "counter", text: Object.keys(answers).length + " / " + questions.length + " answered" }),
            el("span", { class: "kbd-hint", html: "<kbd>A</kbd>–<kbd>D</kbd> · <kbd>F</kbd> flag" }),
          ]),
          el("button", { class: "btn primary small", onclick: submit, text: "Submit exam" }),
        ]));

        var q = questions[pos];
        var picked = answers[q.id] || null;

        function pick(L) { answers[q.id] = L; draw(); }
        function go(delta) {
          pos = Math.max(0, Math.min(questions.length - 1, pos + delta));
          draw();
        }

        bindKeys(function (e) {
          if (typingTarget(e) || e.metaKey || e.ctrlKey || e.altKey) return;
          var key = e.key.toUpperCase();
          if (LETTERS.indexOf(key) !== -1) { e.preventDefault(); pick(key); return; }
          if (e.key === "ArrowRight" || e.key === "n") { e.preventDefault(); go(1); return; }
          if (e.key === "ArrowLeft" || e.key === "p") { e.preventDefault(); go(-1); return; }
          if (e.key === "f") {
            e.preventDefault();
            if (flags[q.id]) delete flags[q.id];
            else flags[q.id] = true;
            draw();
          }
        });

        var card = el("div", { class: "qcard" });
        card.appendChild(el("div", { class: "progressline" }, [
          el("i", { style: "width:" + ((pos + 1) / questions.length * 100) + "%" }),
        ]));
        card.appendChild(el("div", { class: "qmeta" }, [
          q.scenario ? el("span", { class: "scenario", text: q.scenario }) : null,
          q.studyArea ? el("span", { class: "tag", text: q.studyArea }) : null,
          el("button", {
            class: "flag-btn" + (flags[q.id] ? " on" : ""),
            onclick: function () {
              if (flags[q.id]) delete flags[q.id];
              else flags[q.id] = true;
              draw();
            },
            text: flags[q.id] ? "Flagged" : "Flag",
          }),
        ]));
        card.appendChild(el("div", { class: "stem", text: q.stem }));
        var opts = el("div", { class: "options", role: "group", "aria-label": "Answer choices" });
        LETTERS.forEach(function (L) {
          opts.appendChild(el("button", {
            class: "opt" + (picked === L ? " selected" : ""),
            onclick: function () { pick(L); },
          }, [
            el("span", { class: "key", text: L }),
            el("span", { text: q.options[L] }),
          ]));
        });
        card.appendChild(opts);
        card.appendChild(el("div", { class: "qnav" }, [
          el("button", {
            class: "btn",
            disabled: pos === 0 ? "disabled" : null,
            onclick: function () { go(-1); },
            text: "← Previous",
          }),
          el("span", { class: "counter", text: "Question " + (pos + 1) + " of " + questions.length }),
          pos >= questions.length - 1
            ? el("button", { class: "btn primary", onclick: submit, text: "Finish & score" })
            : el("button", { class: "btn primary", onclick: function () { go(1); }, text: "Next →" }),
        ]));
        wrap.appendChild(card);

        var grid = el("div", { class: "qgrid", "aria-label": "Question navigator" });
        questions.forEach(function (qq, idx) {
          grid.appendChild(el("button", {
            class: (answers[qq.id] ? "answered " : "") + (flags[qq.id] ? "flagged " : "") + (idx === pos ? "current" : ""),
            onclick: function () { pos = idx; draw(); },
            text: String(idx + 1),
            title: flags[qq.id] ? "Flagged" : (answers[qq.id] ? "Answered" : "Unanswered"),
          }));
        });
        wrap.appendChild(el("div", { style: "margin-top:16px" }, [
          el("div", { class: "track-meta", text: "Jump to question:" }),
          grid,
        ]));
      }

      function results() {
        clear(wrap);
        var correct = 0;
        var perDomain = {};
        var skipped = 0;
        questions.forEach(function (q) {
          if (!answers[q.id]) skipped++;
          var ok = answers[q.id] === q.answer;
          if (ok) correct++;
          var d = perDomain[q.domain] = perDomain[q.domain] || { c: 0, t: 0 };
          d.t++;
          if (ok) d.c++;
        });
        var frac = correct / questions.length;
        var scaled = Math.round(exam.meta.scaleMin + frac * (exam.meta.scaleMax - exam.meta.scaleMin));
        var pass = scaled >= exam.meta.passScaled;
        var best = store.examBest[exam.examId];
        if (!best || scaled > best.scaled) {
          store.examBest[exam.examId] = {
            scaled: scaled, pass: pass, correct: correct, total: questions.length,
          };
          persist();
        }

        var reviewMode = "misses"; // misses | all | flagged

        function drawResults() {
          clear(wrap);
          wrap.appendChild(crumb(exam, "Results"));
          wrap.appendChild(modeNav(exam, "exam"));
          wrap.appendChild(el("div", { class: "result-hero" }, [
            el("div", { class: "track-meta", text: "Approximate scaled score" }),
            el("div", { class: "score", text: String(scaled) }),
            el("span", { class: "verdict-badge " + (pass ? "pass" : "fail"), text: pass ? "PASS" : "BELOW PASS" }),
            el("p", {
              class: "track-meta",
              text: correct + " of " + questions.length + " correct (" + Math.round(frac * 100) + "%) · " +
                fmt(seconds) + (skipped ? " · " + skipped + " skipped" : "") + " · pass mark " + exam.meta.passScaled,
            }),
            el("div", { class: "mode-row", style: "justify-content:center;margin-top:14px" }, [
              el("button", { class: "btn primary", onclick: function () { setup(); }, text: "Take another" }),
              el("a", { class: "btn", href: "#/practice/" + exam.examId, text: "Practice weak areas" }),
              el("a", { class: "btn", href: "#/flashcards/" + exam.examId, text: "Drill flashcards" }),
            ]),
          ]));

          var table = el("table", { class: "domain-table" });
          table.appendChild(el("thead", {}, [
            el("tr", {}, [
              el("th", { text: "Domain" }),
              el("th", { text: "Coverage" }),
              el("th", { class: "num", text: "Score" }),
            ]),
          ]));
          var tbody = el("tbody");
          (exam.domains || []).forEach(function (d) {
            var s = perDomain[d.id];
            if (!s) return;
            var pct = Math.round(s.c / s.t * 100);
            tbody.appendChild(el("tr", {}, [
              el("td", { text: d.name }),
              el("td", {}, [el("div", { class: "bar" }, [el("i", { style: "width:" + pct + "%" })])]),
              el("td", { class: "num", text: s.c + "/" + s.t + " (" + pct + "%)" }),
            ]));
          });
          table.appendChild(tbody);
          wrap.appendChild(el("h3", { text: "By domain" }));
          wrap.appendChild(table);

          var reviewPool = questions.filter(function (q) {
            if (reviewMode === "all") return true;
            if (reviewMode === "flagged") return !!flags[q.id];
            return answers[q.id] !== q.answer;
          });

          wrap.appendChild(el("h3", { text: "Review" }));
          var filters = el("div", { class: "review-filter" });
          [
            ["misses", "Misses & skips"],
            ["flagged", "Flagged"],
            ["all", "All questions"],
          ].forEach(function (pair) {
            filters.appendChild(el("button", {
              class: "btn small" + (reviewMode === pair[0] ? " primary" : ""),
              onclick: function () { reviewMode = pair[0]; drawResults(); },
              text: pair[1],
            }));
          });
          wrap.appendChild(filters);

          if (!reviewPool.length) {
            wrap.appendChild(el("div", { class: "empty-state" }, [
              el("h3", { text: "Nothing to review here" }),
              el("p", { text: reviewMode === "misses" ? "You got every question right. Nice work." : "No items match this filter." }),
            ]));
            return;
          }

          reviewPool.forEach(function (q) {
            var yours = answers[q.id];
            var ok = yours === q.answer;
            wrap.appendChild(el("div", { class: "qcard miss-card" }, [
              el("div", { class: "qmeta" }, [
                q.studyArea ? el("span", { class: "tag", text: q.studyArea }) : null,
                el("span", { class: "tag", text: ok ? "Correct" : (yours ? "Incorrect" : "Skipped") }),
                domainName(exam, q.domain) ? el("span", { class: "tag", text: domainName(exam, q.domain) }) : null,
              ]),
              el("p", { class: "stem", text: q.stem }),
              el("p", { html: "<strong>Correct: " + q.answer + ".</strong> " + escapeHtml(q.options[q.answer]) }),
              yours && !ok
                ? el("p", { class: "why", html: "You chose " + yours + ": " + escapeHtml(q.options[yours] || "") })
                : (!yours ? el("p", { class: "why", text: "You skipped this one." }) : null),
              el("p", { text: q.explanationCorrect }),
              q.reference
                ? el("p", { class: "why" }, [el("a", { href: q.reference, target: "_blank", rel: "noopener", text: "Reference ↗" })])
                : null,
            ]));
          });
        }

        drawResults();
      }

      draw();
    }

    setup();
  }

  // ---- flashcards ---------------------------------------------------------
  function renderFlashcards(exam) {
    var cards = exam.flashcards || [];
    var known = (store.flash[exam.examId] = store.flash[exam.examId] || { known: {} }).known;
    var domainFilter = "all";
    var order = shuffle(cards);
    var idx = 0, flipped = false;
    var wrap = el("div", { class: "view-enter" });
    appEl.appendChild(wrap);

    function pool() {
      return order.filter(function (c) {
        return domainFilter === "all" || c.domain === domainFilter;
      });
    }

    function draw() {
      clear(wrap);
      wrap.appendChild(crumb(exam, "Flashcards"));
      wrap.appendChild(modeNav(exam, "flashcards"));
      if (!cards.length) {
        wrap.appendChild(el("div", { class: "empty-state" }, [
          el("h3", { text: "No flashcards yet" }),
          el("p", { text: "This track doesn’t have a flashcard set bundled." }),
        ]));
        return;
      }

      var sel = el("select", {
        "aria-label": "Filter by domain",
        onchange: function (e) { domainFilter = e.target.value; idx = 0; flipped = false; draw(); },
      });
      sel.appendChild(el("option", { value: "all", text: "All domains" }));
      (exam.domains || []).forEach(function (d) {
        sel.appendChild(el("option", { value: d.id, text: d.name }));
      });
      sel.value = domainFilter;

      var p = pool();
      var knownCount = p.filter(function (c) { return known[hashStr(c.front)]; }).length;
      wrap.appendChild(el("div", { class: "toolbar" }, [
        el("div", { class: "group" }, [sel]),
        el("div", { class: "group" }, [
          el("span", { class: "counter", text: knownCount + " / " + p.length + " known" }),
          el("span", { class: "kbd-hint", html: "<kbd>Space</kbd> flip · <kbd>1</kbd> miss · <kbd>2</kbd> got it" }),
          el("button", {
            class: "btn small ghost",
            onclick: function () { order = shuffle(cards); idx = 0; flipped = false; draw(); },
            text: "Shuffle",
          }),
          el("button", {
            class: "btn small ghost",
            onclick: function () {
              p.forEach(function (c) { delete known[hashStr(c.front)]; });
              persist();
              draw();
            },
            text: "Reset",
          }),
        ]),
      ]));

      if (!p.length) {
        wrap.appendChild(el("div", { class: "empty-state" }, [
          el("h3", { text: "No cards in this domain" }),
          el("p", { text: "Pick another domain filter." }),
        ]));
        return;
      }
      if (idx >= p.length) idx = 0;
      var card = p[idx];

      function next(markKnown) {
        if (markKnown) known[hashStr(card.front)] = true;
        else delete known[hashStr(card.front)];
        persist();
        idx = (idx + 1) % p.length;
        flipped = false;
        draw();
      }

      bindKeys(function (e) {
        if (typingTarget(e) || e.metaKey || e.ctrlKey || e.altKey) return;
        if (e.key === " " || e.key === "Enter") {
          e.preventDefault();
          flipped = !flipped;
          draw();
          return;
        }
        if (e.key === "1" || e.key === "x" || e.key === "X") { e.preventDefault(); next(false); return; }
        if (e.key === "2" || e.key === "g" || e.key === "G") { e.preventDefault(); next(true); }
      });

      var fc = el("div", {
        class: "flashcard" + (flipped ? " flipped" : ""),
        role: "button",
        tabindex: "0",
        "aria-label": flipped ? "Flashcard back. Activate to flip." : "Flashcard front. Activate to flip.",
        onclick: function () { flipped = !flipped; draw(); },
      }, [
        el("div", { class: "flash-inner" }, [
          el("div", { class: "flash-face front" }, [
            el("div", {}, [
              el("div", { text: card.front }),
              el("div", { class: "hint", text: "Space or click to flip" }),
            ]),
          ]),
          el("div", { class: "flash-face back" }, [
            el("div", {}, [
              el("div", { text: card.back }),
              el("div", { class: "hint", text: card.domain ? domainName(exam, card.domain) : "" }),
            ]),
          ]),
        ]),
      ]);

      wrap.appendChild(el("div", { class: "flash-wrap" }, [
        fc,
        el("div", { class: "counter", text: "Card " + (idx + 1) + " of " + p.length }),
        el("div", { class: "mode-row flash-actions" }, [
          el("button", { class: "btn", onclick: function () { next(false); }, text: "Missed" }),
          el("button", { class: "btn", onclick: function () { flipped = !flipped; draw(); }, text: "Flip" }),
          el("button", { class: "btn primary", onclick: function () { next(true); }, text: "Got it" }),
        ]),
      ]));
    }
    draw();
  }

  // ---- boot ---------------------------------------------------------------
  function loadExamData() {
    AU.exams = AU.exams || {};
    var pending = CATALOG.filter(function (c) { return !AU.exams[c.examId]; });
    if (!pending.length) return Promise.resolve();
    return Promise.all(pending.map(function (c) {
      return new Promise(function (resolve) {
        var s = document.createElement("script");
        s.src = "data/" + c.examId + ".js";
        s.onload = resolve;
        s.onerror = resolve;
        document.head.appendChild(s);
      });
    }));
  }

  clear(appEl);
  appEl.appendChild(loadingView());
  loadExamData().then(function () {
    AU = window.AU;
    CATALOG = AU.index || CATALOG;
    render();
  });
