  // ---- markdown (compact, covers our study-guide subset) ------------------
  var CODE_OPEN = "@@AUCODE", CODE_CLOSE = "AUCODE@@";
  function mdInline(s) {
    s = String(s == null ? "" : s);
    var codes = [];
    s = s.replace(/`([^`]+)`/g, function (_, c) {
      codes.push(c);
      return CODE_OPEN + (codes.length - 1) + CODE_CLOSE;
    });
    s = escapeHtml(s);
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)\)/g, function (_, t, u) {
      return '<a href="' + u + '" target="_blank" rel="noopener">' + t + "</a>";
    });
    s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    s = s.replace(/(^|[^*])\*([^*]+)\*/g, "$1<em>$2</em>");
    s = s.replace(new RegExp(CODE_OPEN + "(\\d+)" + CODE_CLOSE, "g"), function (_, i) {
      return "<code>" + escapeHtml(codes[+i]) + "</code>";
    });
    return s;
  }
  function renderMarkdown(md) {
    var lines = String(md || "").replace(/\r\n/g, "\n").split("\n");
    var out = [], i = 0;
    function flushList(type, items) {
      out.push("<" + type + ">" + items.map(function (t) {
        return "<li>" + mdInline(t) + "</li>";
      }).join("") + "</" + type + ">");
    }
    while (i < lines.length) {
      var line = lines[i];
      if (/^```/.test(line)) {
        var buf = []; i++;
        while (i < lines.length && !/^```/.test(lines[i])) { buf.push(lines[i]); i++; }
        i++;
        out.push("<pre><code>" + escapeHtml(buf.join("\n")) + "</code></pre>");
        continue;
      }
      var h = line.match(/^(#{1,4})\s+(.*)$/);
      if (h) {
        var lvl = h[1].length;
        out.push("<h" + lvl + ">" + mdInline(h[2]) + "</h" + lvl + ">");
        i++;
        continue;
      }
      if (/^\s*>/.test(line)) {
        var q = [];
        while (i < lines.length && /^\s*>/.test(lines[i])) {
          q.push(lines[i].replace(/^\s*>\s?/, ""));
          i++;
        }
        out.push("<blockquote>" + mdInline(q.join(" ")) + "</blockquote>");
        continue;
      }
      if (/^\s*\|.*\|\s*$/.test(line) && i + 1 < lines.length && /^\s*\|?[\s:\-|]+\|?\s*$/.test(lines[i + 1])) {
        var rows = [];
        while (i < lines.length && /\|/.test(lines[i]) && lines[i].trim()) {
          rows.push(lines[i]);
          i++;
        }
        var cells = function (r) {
          return r.trim().replace(/^\|/, "").replace(/\|$/, "").split("|").map(function (c) { return c.trim(); });
        };
        var head = cells(rows[0]);
        var body = rows.slice(2).map(cells);
        var t = "<table><thead><tr>" + head.map(function (c) {
          return "<th>" + mdInline(c) + "</th>";
        }).join("") + "</tr></thead><tbody>";
        t += body.map(function (r) {
          return "<tr>" + r.map(function (c) {
            return "<td>" + mdInline(c) + "</td>";
          }).join("") + "</tr>";
        }).join("");
        out.push(t + "</tbody></table>");
        continue;
      }
      if (/^\s*[-*]\s+/.test(line)) {
        var ul = [];
        while (i < lines.length && /^\s*[-*]\s+/.test(lines[i])) {
          ul.push(lines[i].replace(/^\s*[-*]\s+/, ""));
          i++;
        }
        flushList("ul", ul);
        continue;
      }
      if (/^\s*\d+\.\s+/.test(line)) {
        var ol = [];
        while (i < lines.length && /^\s*\d+\.\s+/.test(lines[i])) {
          ol.push(lines[i].replace(/^\s*\d+\.\s+/, ""));
          i++;
        }
        flushList("ol", ol);
        continue;
      }
      if (/^\s*(---|\*\*\*|___)\s*$/.test(line)) { out.push("<hr>"); i++; continue; }
      if (!line.trim()) { i++; continue; }
      var para = [line]; i++;
      while (i < lines.length && lines[i].trim() && !/^(#{1,4}\s|```|\s*[-*]\s|\s*\d+\.\s|\s*>|\s*\|)/.test(lines[i])) {
        para.push(lines[i]);
        i++;
      }
      out.push("<p>" + mdInline(para.join(" ")) + "</p>");
    }
    return out.join("\n");
  }

  // ---- progress ring ------------------------------------------------------
  function ring(pct) {
    var C = 138.23, off = C * (1 - pct / 100);
    var svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("class", "ring");
    svg.setAttribute("viewBox", "0 0 54 54");
    svg.setAttribute("aria-hidden", "true");
    svg.innerHTML =
      '<circle class="track-bg" cx="27" cy="27" r="22" fill="none" stroke-width="5"/>' +
      '<circle class="track-fg" cx="27" cy="27" r="22" fill="none" stroke-width="5" stroke-linecap="round" ' +
      'transform="rotate(-90 27 27)" stroke-dasharray="' + C + '" stroke-dashoffset="' + off + '"/>' +
      '<text x="27" y="31" text-anchor="middle">' + Math.round(pct) + "%</text>";
    return svg;
  }

